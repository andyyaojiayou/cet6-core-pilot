const listeningSections = {
  1: '长对话 1', 5: '长对话 2', 9: '短文 1', 12: '短文 2',
  16: '讲座 1', 19: '讲座 2', 22: '讲座 3',
};
const readingSections = { a: '选词填空', b: '长篇匹配阅读', c: '仔细阅读' };

function examDate(paper) {
  const [year, month, set] = paper.split('-');
  return `${year} 年 ${Number(month)} 月第 ${set} 套（懒笔记编号）`;
}
function transcript(paper, anchor, form) {
  return {
    kind: 'transcript', form, label: `${examDate(paper)} · ${listeningSections[anchor.split('-')[1]]}文字稿`,
    url: `${host}/sections/listening/${paper}/#${anchor}`,
  };
}
function reading(paper, anchor, form) {
  return {
    kind: 'reading', form, label: `${examDate(paper)} · ${readingSections[anchor.split('-')[3]]}正文`,
    url: `${host}/paper/${paper}/#${anchor}`,
  };
}
function relation(kind, term, ipa, meaning, comparison, example, translation, ipaUS) {
  return { kind, term, ipa, ...(ipaUS && { ipaUS }), meaning, comparison, example, translation };
}
function recall(skill, word, distractors) {
  return { hint: '记住搭配 ' + word.collocation, ...word, skills: [skill], distractors };
}
function write(word, phraseCue, ...accept) {
  return {
    hint: '记住搭配 ' + word.collocation,
    ...word, skills: ['writing'], cue: `${word.meaning}（${word.pos}），以 ${word.id[0]} 开头`,
    phraseCue, accept: accept.length ? accept : [word.collocation],
  };
}

