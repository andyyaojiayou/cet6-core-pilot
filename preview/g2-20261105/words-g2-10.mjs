const lazy = 'https://english-exam.lazynote.cn/cet6';
function date(paper) {
  const [year, month, set] = paper.split('-');
  return year + ' 年 ' + Number(month) + ' 月第 ' + set + ' 套';
}
const listening = (paper, part, anchor, form) => ({
  kind: 'transcript', label: date(paper) + ' · ' + part + '文字稿', form,
  url: lazy + '/sections/listening/' + paper + '/#' + anchor,
});
const reading = (paper, passage, paragraph, form) => ({
  kind: 'reading', label: date(paper) + ' · 仔细阅读第 ' + passage + ' 篇正文', form,
  url: lazy + '/paper/' + paper + '/#p-part3-section-c-' + passage + '-' + paragraph,
});
const related = (kind, term, ipa, meaning, comparison, example, translation, ipaUS) =>
  ({ kind, term, ipa, meaning, comparison, example, translation, ...(ipaUS ? { ipaUS } : {}) });

