const base = 'https://english-exam.lazynote.cn/cet6';

function date(paper) {
  const [year, month, set] = paper.split('-');
  return year + ' 年 ' + Number(month) + ' 月第 ' + set + ' 套';
}

function listening(paper, part, anchor, form) {
  return { kind: 'transcript', label: date(paper) + ' · ' + part + '文字稿', form, url: base + '/sections/listening/' + paper + '/#' + anchor };
}

function reading(paper, passage, paragraph, form) {
  return { kind: 'reading', label: date(paper) + ' · 仔细阅读第 ' + passage + ' 篇正文', form,
    url: base + '/paper/' + paper + '/#p-part3-section-c-' + passage + '-' + paragraph };
}

function related(kind, term, ipa, meaning, comparison, example, translation, ipaUS) {
  return { kind, term, ipa, meaning, comparison, example, translation, ...(ipaUS ? { ipaUS } : {}) };
}

