const base = 'https://english-exam.lazynote.cn/cet6';

function examDate(paper) {
  const [year, month, set] = paper.split('-');
  return `${year} 年 ${Number(month)} 月第 ${set} 套`;
}

function reading(paper, anchor, form) {
  const section = anchor[0];
  const part = section === 'a' ? '选词填空' : section === 'b' ? '长篇阅读'
    : `仔细阅读第 ${anchor.startsWith('c-2-') ? '2' : '1'} 篇`;
  return {
    kind: 'reading', label: `${examDate(paper)} · ${part}正文`, form,
    url: `${base}/paper/${paper}/#p-part3-section-${anchor}`,
  };
}

function transcript(paper, anchor, form) {
  const parts = { 1: '长对话 1', 5: '长对话 2', 9: '短文 1', 12: '短文 2', 16: '讲座 1', 19: '讲座 2', 22: '讲座 3' };
  const part = parts[anchor.split('-')[0]];
  return {
    kind: 'transcript', label: `${examDate(paper)} · ${part}文字稿`, form,
    url: `${base}/sections/listening/${paper}/#p-${anchor}`,
  };
}

function compare(kind, term, ipa, meaning, comparison, example, translation, ipaUS) {
  return { kind, term, ipa, meaning, comparison, example, translation, ...(ipaUS ? { ipaUS } : {}) };
}

function sense(id, pos, meaning, collocation, example, translation, context, evidence, pronunciation = {}) {
  return { id, pos, meaning, collocation, example, translation, context, ...(evidence ? { evidence } : {}), ...pronunciation };
}

function verb(past, participle = past) {
  return { past, participle };
}

function choose(...distractors) {
  return { distractors };
}

function write(cue, phraseCue, ...accept) {
  return { cue, phraseCue, accept };
}

function word(id, skill, theme, pos, ipa, details, evidence, related, task, extra = {}) {
  const [meaning, collocation, sentence, translation, context, hint] = details;
  const tier = extra.senses?.some(entry => entry.evidence?.length) ? 'A' : 'B';
  return { id, tier, skills: [skill], theme, pos, ipa, meaning, collocation, sentence, translation,
    context, hint, evidence, related, ...task, ...extra };
}

