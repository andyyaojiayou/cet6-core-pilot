const lazy = 'https://english-exam.lazynote.cn/cet6';

function examDate(paper) {
  const [year, month, set] = paper.split('-');
  return `${year} 年 ${Number(month)} 月第 ${set} 套`;
}

function reading(paper, section, paragraph, form) {
  const sectionLabel = {
    a: '选词填空印刷正文',
    b: '长篇匹配正文',
    'c-1': '仔细阅读第 1 篇正文',
    'c-2': '仔细阅读第 2 篇正文',
  }[section];
  return {
    kind: 'reading', label: `${examDate(paper)} · ${sectionLabel}第 ${paragraph} 段`, form,
    url: `${lazy}/paper/${paper}/part3-section-${section}/#p-${paragraph}`,
  };
}

function transcript(paper, section, anchor, form) {
  return {
    kind: 'transcript', label: `${examDate(paper)} · ${section}文字稿`, form,
    url: `${lazy}/sections/listening/${paper}/#${anchor}`,
  };
}

