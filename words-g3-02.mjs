function dateLabel(paper) {
  const [year, month, set] = paper.split('-');
  return `${year} 年 ${Number(month)} 月第 ${set} 套（懒笔记编号）`;
}

function listening(paper, anchor, form) {
  const section = sections[anchor.split('-')[1]];
  return {
    kind: 'transcript', form, label: `${dateLabel(paper)} · ${section}文字稿`,
    url: `${source}/sections/listening/${paper}/#${anchor}`,
  };
}

function reading(paper, anchor, form) {
  const section = { a: '选词填空', b: '长篇匹配阅读', c: '仔细阅读' }[anchor.split('-')[3]];
  return {
    kind: 'reading', form, label: `${dateLabel(paper)} · ${section}正文`,
    url: `${source}/paper/${paper}/#${anchor}`,
  };
}

