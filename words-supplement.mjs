const base = 'https://english-exam.lazynote.cn/cet6';

function listening(paper, section, anchor, form) {
  const [year, month, set] = paper.split('-');
  return { kind: 'transcript', form, url: `${base}/sections/listening/${paper}/#${anchor}`,
    label: `${year} 年 ${Number(month)} 月第 ${set} 套（懒笔记编号） · ${section}文字稿` };
}

function reading(paper, section, anchor, form) {
  const [year, month, set] = paper.split('-');
  return { kind: 'reading', form, url: `${base}/paper/${paper}/#${anchor}`,
    label: `${year} 年 ${Number(month)} 月第 ${set} 套（懒笔记编号） · ${section}正文` };
}

